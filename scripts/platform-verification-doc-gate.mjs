#!/usr/bin/env node
/**
 * scripts/platform-verification-doc-gate.mjs — machine parity between the platform ladder and its doc.
 *
 * ROLE
 * ----
 * `docs/public/PLATFORM_VERIFICATION.md` tells a human which commands constitute the host
 * verification ladder. `scripts/platform-verify.mjs` decides which commands actually run.
 *
 * The fix is not "remember to update the doc". It is this gate: the generated regions below are
 * rendered FROM the script itself, so a command or option added to `platform-verify.mjs` and not
 * reflected in the doc fails `pnpm docs:check`. Same contract as
 * `scripts/generate-debug-api-reference.mjs --check`.
 *
 * SOURCE OF TRUTH
 * ---------------
 * The real script, spawned — never a re-implementation of its tables, which would be a second list
 * free to drift in exactly the same way:
 *   `platform-verify.mjs --dry-run --json`                    -> core-tier plan
 *   `platform-verify.mjs --dry-run --json --include-extended` -> extended-tier plan
 *   `platform-verify.mjs --help`                              -> the accepted options
 *
 * WHAT IS GENERATED (everything else in the doc stays hand-written prose)
 * ----------------------------------------------------------------------
 *   required-commands  the per-host ladder, in plan order, as the exact shell lines to run
 *   extended-commands  required commands that only plan under --include-extended
 *   optional-commands  checkout-gated commands and the env vars that enable them
 *   options            the verbatim `--help` option list
 *
 * Each region is delimited by HTML comments, which Markdown does not render:
 *   <!-- platform-verify:<region> generated by scripts/platform-verification-doc-gate.mjs -->
 *   ...generated body...
 *   <!-- /platform-verify:<region> -->
 *
 * USAGE
 * -----
 *   node scripts/platform-verification-doc-gate.mjs           # rewrite the generated regions
 *   node scripts/platform-verification-doc-gate.mjs --check   # fail on drift (wired into docs:check)
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scriptPath = resolve(repoRoot, "scripts/platform-verify.mjs");
const docPath = resolve(repoRoot, "docs/public/PLATFORM_VERIFICATION.md");
const checkOnly = process.argv.includes("--check");

const corePlan = runPlan([]);
const extendedPlan = runPlan(["--include-extended"]);
const helpText = runHelp();

const coreIds = new Set(corePlan.commands.map((command) => command.id));
const requiredCore = corePlan.commands.filter((command) => command.required === true);
const requiredExtended = extendedPlan.commands.filter((command) => command.required === true && !coreIds.has(command.id));
const optional = extendedPlan.commands.filter((command) => command.required !== true);

if (requiredCore.length === 0) {
  throw new Error("platform-verify planned no required commands; the ladder cannot be empty.");
}

const regions = {
  "required-commands": fence("bash", requiredCore.map((command) => command.command.join(" "))),
  "extended-commands": fence("bash", [
    ...requiredExtended.map((command) => command.command.join(" ")),
    "# ...or through the runner, so the host receipt records them alongside the core tier:",
    "pnpm run platform:verify -- --run --include-extended --host-id <id>"
  ]),
  "optional-commands": optional.map((command) => `- \`${command.id}\` requires ${envList(command.requiresEnv)}.`),
  options: fence("text", helpText)
};

const original = readFileSync(docPath, "utf8");
let updated = original;
for (const [name, lines] of Object.entries(regions)) {
  updated = replaceRegion(updated, name, lines);
}

if (!checkOnly) {
  if (updated !== original) writeFileSync(docPath, updated, "utf8");
  process.stdout.write(`platform-verification doc regions written: ${Object.keys(regions).join(", ")}\n`);
} else if (updated !== original) {
  throw new Error(
    "docs/public/PLATFORM_VERIFICATION.md disagrees with scripts/platform-verify.mjs.\n"
    + `${firstDifference(original, updated)}\n`
    + "Run `node scripts/platform-verification-doc-gate.mjs` and commit the result."
  );
} else {
  process.stdout.write(
    `platform-verification doc matches the plan: ${requiredCore.length} required, `
    + `${requiredExtended.length} extended, ${optional.length} optional.\n`
  );
}

/** Spawn the real planner and return its receipt. A non-zero exit is a gate failure, not a warning. */
function runPlan(extraArgs) {
  const result = spawnSync(process.execPath, [scriptPath, "--dry-run", "--json", ...extraArgs], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024
  });
  if (result.status !== 0) {
    throw new Error(`platform-verify --dry-run --json ${extraArgs.join(" ")} failed: ${result.stderr || result.stdout}`);
  }
  const receipt = JSON.parse(result.stdout);
  if (!Array.isArray(receipt.commands)) {
    throw new Error("platform-verify plan JSON has no commands array; the gate cannot compare against it.");
  }
  for (const command of receipt.commands) {
    if (typeof command.id !== "string" || !Array.isArray(command.command)) {
      throw new Error(`platform-verify plan entry is missing id/command: ${JSON.stringify(command)}`);
    }
  }
  return receipt;
}

/** The script's own option list, so the doc cannot advertise a flag the parser does not accept. */
function runHelp() {
  const result = spawnSync(process.execPath, [scriptPath, "--help"], { cwd: repoRoot, encoding: "utf8" });
  if (result.status !== 0) throw new Error(`platform-verify --help failed: ${result.stderr || result.stdout}`);
  const lines = result.stdout.replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((line) => line.trim() === "Options:");
  if (start < 0) throw new Error("platform-verify --help did not print an Options: block.");
  const options = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "") break;
    options.push(line.replace(/\s+$/, ""));
  }
  if (options.length === 0) throw new Error("platform-verify --help printed an empty Options: block.");
  return options;
}

function envList(values) {
  const names = Array.isArray(values) ? values : [];
  if (names.length === 0) return "no host environment";
  const quoted = names.map((name) => `\`${name}\``);
  return quoted.length === 1 ? quoted[0] : `${quoted.slice(0, -1).join(", ")} and ${quoted[quoted.length - 1]}`;
}

function fence(language, lines) {
  return [`\`\`\`${language}`, ...lines, "```"];
}

/**
 * Replace one delimited region's body. A missing marker pair is a hard failure rather than a silent
 * no-op: a gate that quietly stops checking is worse than no gate.
 */
function replaceRegion(source, name, lines) {
  const open = `<!-- platform-verify:${name} generated by scripts/platform-verification-doc-gate.mjs -->`;
  const close = `<!-- /platform-verify:${name} -->`;
  const openIndex = source.indexOf(open);
  const closeIndex = source.indexOf(close);
  if (openIndex < 0 || closeIndex < 0 || closeIndex < openIndex) {
    throw new Error(`docs/public/PLATFORM_VERIFICATION.md is missing the ${name} markers:\n${open}\n...\n${close}`);
  }
  const body = `${open}\n\n${lines.join("\n")}\n\n`;
  return `${source.slice(0, openIndex)}${body}${source.slice(closeIndex)}`;
}

/** First differing line, so the failure names the drift instead of asking for a manual diff. */
function firstDifference(actual, expected) {
  const actualLines = actual.split("\n");
  const expectedLines = expected.split("\n");
  for (let index = 0; index < Math.max(actualLines.length, expectedLines.length); index += 1) {
    if (actualLines[index] !== expectedLines[index]) {
      return `First difference at line ${index + 1}:\n  doc:  ${JSON.stringify(actualLines[index] ?? null)}\n  plan: ${JSON.stringify(expectedLines[index] ?? null)}`;
    }
  }
  return "Files differ only in trailing content.";
}
